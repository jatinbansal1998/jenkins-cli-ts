export type ErrorCode = keyof typeof ERROR_EXIT_CODES;

export function exitCodeFor(error: unknown): ExitCode {
  return error instanceof CliError
    ? ERROR_EXIT_CODES[error.code]
    : EXIT_CODES.FAILURE;
}
