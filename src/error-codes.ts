/**
 * Error codes and process exit codes. Both are part of the public contract:
 * `--json` errors carry the error code, and the exit code is derived from it,
 * so scripts can branch on either without parsing text. The README documents
 * the exit code table; keep the two in sync.
 */
import { CliError } from "./cli";

export const EXIT_CODES = {
  SUCCESS: 0,
  /** The build or operation finished unsuccessfully, or an unclassified error. */
  FAILURE: 1,
  USAGE: 2,
  AUTH: 3,
  NOT_FOUND: 4,
  PROTECTED_PROFILE: 5,
  /** Jenkins could not be reached, timed out, or answered with an error. */
  JENKINS: 6,
  TIMEOUT: 124,
  INTERRUPTED: 130,
} as const;

export type ExitCode = (typeof EXIT_CODES)[keyof typeof EXIT_CODES];

